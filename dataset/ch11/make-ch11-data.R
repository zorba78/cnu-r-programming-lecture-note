# ---- 2. 학과 행사 만족도 조사: 같은 설문, 세 가지 형식 ---------------------------------

survey <- data.frame(
  응답번호 = 1:12,
  성별 = c(1, 2, 2, 1, 2, 1, 2, 2, 1, 1, 2, 1),
  학년 = c(2, 3, 2, 4, 1, 2, 3, 3, 2, 4, 1, 2),
  참가일 = as.Date(c("2026-09-01", "2026-09-01", "2026-09-02", "2026-09-02", NA, "2026-09-02",
                  "2026-09-03", "2026-09-03", "2026-09-01", "2026-09-03", "2026-09-02", "2026-09-03")),
  만족도 = c(4, 5, 3, 9, 4, 5, 2, 4, 9, 3, 5, 4)
)

# 2-1. Excel: 제목 줄, 날짜 열의 '미정', 안내 시트
wb <- createWorkbook()
addWorksheet(wb, "응답")
writeData(wb, "응답", "2026 학과 행사 만족도 조사 (교육용 가상 자료)", startRow = 1)
writeData(wb, "응답", survey, startRow = 3)
writeData(wb, "응답", "미정", startCol = 4, startRow = 3 + which(is.na(survey$참가일)))
addWorksheet(wb, "안내")
writeData(wb, "안내", data.frame(
  항목 = c("성별", "학년", "참가일", "만족도", "만족도 9"),
  설명 = c("1 = 남, 2 = 여", "1~4 학년", "행사 참가일, 미정은 아직 정하지 않음",
         "1 = 매우 불만족 ~ 5 = 매우 만족", "무응답")
))
saveWorkbook(wb, file.path(out, "survey.xlsx"), overwrite = TRUE)

# 2-2. SPSS: 값 라벨과 사용자 정의 결측값
sav <- survey
sav$성별 <- labelled(survey$성별, c(남 = 1, 여 = 2))
sav$만족도 <- labelled_spss(survey$만족도,
                         c(매우불만족 = 1, 불만족 = 2, 보통 = 3, 만족 = 4, 매우만족 = 5, 무응답 = 9),
                         na_values = 9)
write_sav(sav, file.path(out, "survey.sav"))

# 2-3. CSV: 같은 설문을 그대로 내보낸 파일 (UTF-8)
csv <- survey
csv$참가일 <- ifelse(is.na(survey$참가일), "미정", format(survey$참가일))
write.csv(csv, file.path(out, "survey.csv"), row.names = FALSE, fileEncoding = "UTF-8")

cat("생성 완료:", list.files(out, pattern = "\\.(csv|xlsx|sav)$"), "\n")
