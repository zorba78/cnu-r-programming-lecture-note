# 11장 데이터 입출력 연습 파일 생성 스크립트
#
#   Rscript dataset/ch11/make-ch11-data.R      (프로젝트 폴더에서 실행)
#
# 모든 파일은 교육용 가상 자료다. 도서관 이름, 우편번호, 수치, 설문 응답은 실제와 무관하다.
# 파일마다 일부러 넣어 둔 함정이 있으며, 강의노트 11장이 그 함정을 하나씩 다룬다.
#
#   library-loans.csv  CP949 인코딩. 제목 줄 2개, 앞자리 0 인 우편번호, 점으로 적은 날짜,
#                      천 단위 쉼표가 든 숫자, 휴관 도서관의 '-', 맨 아래 합계 행과 쉼표가 든 주석 행
#   survey.xlsx        첫 줄 제목, 날짜 열에 섞인 글자 '미정', 9 = 무응답 (설명은 '안내' 시트에만 있음)
#   survey.sav         같은 설문의 SPSS 파일. 값 라벨과 사용자 정의 결측값(9) 을 담고 있음
#   survey.csv         같은 설문을 CSV 로 내보낸 파일. 라벨과 결측 정보가 사라지고 숫자 9 만 남음

