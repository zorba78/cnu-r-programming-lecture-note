# 12장 데이터 핸들링 연습 파일 생성 스크립트
#
#   Rscript dataset/ch12/make-ch12-data.R      (프로젝트 폴더에서 실행)
#
# 모든 파일은 교육용 가상 자료다. 도서관 이름, 수치, 인구는 실제와 무관하다(시도 명칭만 실제).
# 11장 library-loans.csv 의 도서관 20곳을 이어받고, 2026년 8월 대출권수는 11장 수치와 같다.
# 파일마다 일부러 넣어 둔 함정이 있으며, 강의노트 12장이 그 함정을 하나씩 다룬다.
#
#   libraries.csv        도서관 기본 정보. 한 행 = 도서관 하나. 시도는 2026년 현재 정식 명칭
#   loans-2026.csv       월별 대출권수(넓은 표). 휴관한 달은 빈칸, 기본 정보에 없는 신규 도서관 한 곳
#   sido-population.csv  다른 기관의 시도별 인구. 2022년 명칭(강원도, 전라북도), 세종 행 중복

out <- "dataset/ch12"
dir.create(out, showWarnings = FALSE, recursive = TRUE)


# ---- 1. 도서관 기본 정보 -------------------------------------------------------------

sido_full <- c(서울 = "서울특별시", 부산 = "부산광역시", 대구 = "대구광역시", 인천 = "인천광역시",
               광주 = "광주광역시", 대전 = "대전광역시", 울산 = "울산광역시", 세종 = "세종특별자치시",
               경기 = "경기도", 강원 = "강원특별자치도", 충북 = "충청북도", 충남 = "충청남도",
               전북 = "전북특별자치도", 전남 = "전라남도", 경북 = "경상북도", 경남 = "경상남도",
               제주 = "제주특별자치도")

