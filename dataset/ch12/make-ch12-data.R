          "2017-01-20", "2008-04-03", "2006-12-14", "2002-10-08", "2019-05-24"),
  열람석 = c(320, 410, 250, 180, 150, 280, 360, 300, 200, 160,
          210, 190, 140, 230, 340, 170, 130, 290, 260, 220)
)
write.csv(libraries, file.path(out, "libraries.csv"), row.names = FALSE, fileEncoding = "UTF-8")


# ---- 2. 월별 대출권수 (넓은 표) -------------------------------------------------------

# 11장의 2026년 8월 대출권수. 여울도서관(L12)은 휴관이라 NA.
aug <- c(48215, 61530, 35108, 22764, 18356, 39427, 44902, 41275, 26843, 17690,
         25318, NA, 15203, 29764, 47831, 21045, 12987, 38420, 33196, 30574)

# 계절에 따른 배율(1월~8월)과 도서관마다 다른 작은 흔들림으로 1~7월 값을 만든다.
season <- c(0.92, 0.85, 0.95, 1.00, 1.03, 0.98, 1.08, 1.00)
set.seed(20260917)
base <- ifelse(is.na(aug), 20480, aug)          # 여울도서관은 휴관 전 수준을 가정
loans <- t(sapply(seq_along(base), function(i)
  round(base[i] * season * c(runif(7, 0.95, 1.05), 1) / season[8])))
loans[, 8] <- aug                                # 8월은 11장 수치 그대로

loans[12, 6:8] <- NA                             # 여울도서관: 6월부터 휴관
loans[14, 2] <- NA                               # 이음도서관: 2월 시설 점검 휴관

months <- sprintf("2026.%02d", 1:8)
colnames(loans) <- months
wide <- data.frame(도서관ID = libraries$도서관ID, 도서관 = libraries$도서관, loans,
                   check.names = FALSE)

# 기본 정보에 아직 등록되지 않은 신규 도서관: 5월 개관
new_lib <- data.frame(도서관ID = "L21", 도서관 = "새솔도서관",
                      matrix(c(NA, NA, NA, NA, 6120, 8735, 9410, 9022), nrow = 1,
                             dimnames = list(NULL, months)),
                      check.names = FALSE)
wide <- rbind(wide, new_lib)
write.csv(wide, file.path(out, "loans-2026.csv"), row.names = FALSE, na = "", fileEncoding = "UTF-8")


