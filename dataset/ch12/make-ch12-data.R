          "별빛도서관", "여울도서관", "바다도서관", "이음도서관", "푸른도서관",
          "물결도서관", "고운도서관", "달빛도서관", "은하도서관", "청솔도서관"),
  시도 = unname(sido_full[c("서울", "서울", "경기", "인천", "강원", "대전", "대전", "세종", "충남", "충남",
